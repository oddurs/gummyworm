#!/usr/bin/env python3
"""Measure how much of its cell each glyph inks, and write lib/coverage.sh.

usage: glyph_coverage.py > lib/coverage.sh

Each glyph is drawn the way the SVG/PNG exporter draws it: 12px 'Courier New',
Courier, monospace in a 7.2 x 14.4 cell, baseline at the bottom of the cell.
It is rasterised white on black at device resolution, and its coverage is the mean
*linear light* over the cell's area. Linear, not the encoded pixel values, because the
eye adds up light: a thin stroke is mostly partly covered pixels, and those are
blended in encoded space, so they emit much less light than their geometric
coverage suggests. Measuring encoded values overstates a glyph's light several
times over. Ink that falls outside the cell, such as a descender, is
counted, because the eye averages over the neighbourhood, not the cell.

Terminals use other fonts, so these are typical values, not exact ones. They
only need to be right about the ordering and the rough spacing.

Emoji are left out: they are coloured bitmaps, so their coverage means nothing.
"""
import subprocess
import sys

FONT_SIZE, CELL_W, CELL_H = 12, 7.2, 14.4
COLS, ROWS = 10, 5
CHARS = [chr(c) for c in range(33, 127)] + list("°░▒▓█⠁⠃⠇⠿⣿·✦★✷✸✹")


def esc(c):
    return {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}.get(c, c)


def coverage(ch):
    """Light output of the glyph as a fraction of a full cell, at device pixels.

    A 10 x 5 block of the glyph is drawn at 1x, so the cells land on different
    sub-pixel offsets (7.2 and 14.4 are not whole pixels) and the result is an
    average over alignments, as it is across a real image.
    """
    width = CELL_W * COLS
    height = CELL_H * ROWS + CELL_H / 2  # room for descenders under the last row
    lines = "".join(
        f'<text x="0" y="{CELL_H * (i + 1)}" fill="#fff" '
        f'font-family="\'Courier New\', Courier, monospace" font-size="{FONT_SIZE}px" '
        f'xml:space="preserve">{esc(ch) * COLS}</text>' for i in range(ROWS))
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">'
           f'<rect width="100%" height="100%" fill="#000"/>{lines}</svg>')
    png = subprocess.run(["rsvg-convert", "-f", "png"], input=svg.encode(),
                         check=True, capture_output=True).stdout
    # White on black, so the red channel is the light. -colorspace RGB makes it
    # linear; do not follow it with -colorspace Gray, which re-encodes.
    mean = subprocess.run(["magick", "png:-", "-alpha", "off", "-colorspace", "RGB",
                           "-format", "%[fx:mean.r]", "info:"],
                          input=png, check=True, capture_output=True).stdout
    return float(mean) * (width * height) / (CELL_W * CELL_H * COLS * ROWS)


def main():
    rows = [(ch, coverage(ch)) for ch in CHARS]
    out = sys.stdout
    out.write('''#!/usr/bin/env bash
# ============================================================================
# gummyworm/lib/coverage.sh - Glyph ink coverage
# ============================================================================
# How much of its character cell each glyph inks, measured in the exporter's
# font. The colour engine uses it to work out how much light a glyph puts out,
# because a glyph covers only part of its cell and the rest shows the
# background. Generated by bench/glyph_coverage.py; do not edit by hand.
# Requires: nothing
# ============================================================================

# Guard against multiple inclusion
[[ -n "${_GUMMYWORM_COVERAGE_LOADED:-}" ]] && return 0
_GUMMYWORM_COVERAGE_LOADED=1

# Print "<glyph><TAB><coverage>" for every measured glyph, space included.
# Usage: glyph_coverage_table
glyph_coverage_table() {
    cat << 'EOF'
''')
